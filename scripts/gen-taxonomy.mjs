#!/usr/bin/env node
// Builds docs/TAXONOMY.md from docs/taxonomy/owasp-mcp.json, and checks the mapping against the check catalogue.
//   node scripts/gen-taxonomy.mjs           writes docs/TAXONOMY.md
//   node scripts/gen-taxonomy.mjs --check   exits 1 if docs/TAXONOMY.md is not what the mapping produces
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
export const MAP_PATH = join(root, 'docs', 'taxonomy', 'owasp-mcp.json');
export const DOC_PATH = join(root, 'docs', 'TAXONOMY.md');
const LEVELS = ['full', 'partial', 'related'];
const rank = (l) => LEVELS.indexOf(l);

/** Problems with a mapping against the catalogue's check IDs; an empty list means it is sound. */
export function validate(map, checkIds) {
  const bad = [];
  const mstg = new Set(map.taxonomies.mstg.tests.map((t) => t.id));
  const top = new Set(map.taxonomies.top10.items.map((t) => t.id));
  for (const id of checkIds) if (!Object.hasOwn(map.checks, id)) bad.push('check ' + id + ' has no mapping entry (use empty lists to say none)');
  for (const id of Object.keys(map.checks)) if (!checkIds.includes(id)) bad.push('the mapping names ' + id + ', which is not a check');
  for (const [id, e] of Object.entries(map.checks)) {
    if (!Array.isArray(e.mstg) || !Array.isArray(e.top10)) { bad.push(id + ' needs mstg and top10 lists'); continue; }
    for (const m of e.mstg) {
      if (!mstg.has(m.id)) bad.push(id + ': ' + m.id + ' is not in the pinned MCP Security Testing Guide list');
      if (!LEVELS.includes(m.level)) bad.push(id + ': ' + m.id + ' has level ' + m.level);
    }
    for (const m of e.top10) {
      if (!top.has(m.id)) bad.push(id + ': ' + m.id + ' is not in the pinned MCP Top 10 list');
      if (!LEVELS.includes(m.level)) bad.push(id + ': ' + m.id + ' has level ' + m.level);
    }
  }
  for (const [id, list] of Object.entries(map.other_tools || {})) {
    if (!mstg.has(id)) bad.push('other_tools: ' + id + ' is not in the pinned MCP Security Testing Guide list');
    for (const o of list) if (!LEVELS.includes(o.level) || !o.tool) bad.push('other_tools ' + id + ' needs a tool and a level');
  }
  return bad;
}

export function render(map) {
  const { mstg, top10 } = map.taxonomies;
  const best = {};
  const by = {};
  for (const [cid, e] of Object.entries(map.checks)) for (const m of e.mstg) { (by[m.id] ||= []).push([cid, m.level]); if (!(m.id in best) || rank(m.level) < rank(best[m.id])) best[m.id] = m.level; }
  const cat = (id) => id.split('-')[0];
  const cats = [...new Set(mstg.tests.map((t) => cat(t.id)))];
  const n = (xs, f) => xs.filter(f).length;
  const row = (c) => { const ts = mstg.tests.filter((t) => cat(t.id) === c); return [c, ts.length, n(ts, (t) => best[t.id] === 'full'), n(ts, (t) => best[t.id] === 'partial'), n(ts, (t) => best[t.id] === 'related'), n(ts, (t) => !best[t.id]), n(ts, (t) => !best[t.id] && map.other_tools[t.id])]; };
  const rows = cats.map(row);
  const sum = (i) => rows.reduce((a, r) => a + r[i], 0);
  const o = [];
  o.push('# Taxonomy coverage', '', '<!-- Generated by scripts/gen-taxonomy.mjs from docs/taxonomy/owasp-mcp.json. Do not edit by hand. -->', '');
  o.push('Which recognised test and risk IDs each mcp-check check touches, so a security reviewer can see what a grade does and does not cover. mcp-check reads a server\'s `tools/list` (and, with `--repo`, the tool definitions in source). It never calls a tool, watches a client or sits in a gateway, so most test cases are outside it. The mapping makes no claim beyond what a check does.', '');
  o.push('Levels: **full** the check does what the test asks; **partial** it does part of it; **related** it looks at the same area without doing the test. No check is mapped full.', '');
  o.push('## Pinned taxonomies', '', '| Taxonomy | Version | Source | Retrieved |', '|---|---|---|---|');
  o.push('| ' + mstg.name + ' (' + mstg.test_count + ' test cases, `MCPSTG-*`) | ' + mstg.version + ': `' + mstg.commit.slice(0, 12) + '` (' + mstg.commit_date + '); ' + mstg.status + ' | [' + mstg.repo.replace('https://github.com/', '') + '](' + mstg.repo + ') | ' + mstg.retrieved + ' |');
  o.push('| ' + top10.name + ' | ' + top10.version + ': `' + top10.commit.slice(0, 12) + '` (' + top10.commit_date + ') | [' + top10.repo.replace('https://github.com/', '') + '](' + top10.repo + ') | ' + top10.retrieved + ' |', '');
  o.push(mstg.attribution + ' ' + top10.attribution + ' Only IDs and short titles are used here; read the tests and items at the sources above.', '');
  o.push('## MCP Security Testing Guide: coverage by category', '', 'Counts are test cases, using the best level any check reaches. The last column counts tests no check touches that another IsoKron tool covers in part (see "Other tools").', '');
  o.push('| Category | Tests | Full | Partial | Related only | Not covered by mcp-check | of which another tool covers in part |', '|---|---:|---:|---:|---:|---:|---:|');
  for (const r of rows) o.push('| ' + r.join(' | ') + ' |');
  o.push('| **All** | **' + sum(1) + '** | **' + sum(2) + '** | **' + sum(3) + '** | **' + sum(4) + '** | **' + sum(5) + '** | **' + sum(6) + '** |', '');
  o.push('## OWASP MCP Top 10: checks per item', '', '| Item | Title | Checks: full | partial | related | Check IDs |', '|---|---|---:|---:|---:|---|');
  for (const it of top10.items) {
    const hits = Object.entries(map.checks).flatMap(([cid, e]) => e.top10.filter((m) => m.id === it.id).map((m) => [cid, m.level]));
    const c = (l) => hits.filter((h) => h[1] === l).length;
    o.push('| ' + it.id + ' | ' + it.title.replace(/ \(file name.*$/, '') + ' | ' + c('full') + ' | ' + c('partial') + ' | ' + c('related') + ' | ' + (hits.map((h) => '`' + h[0] + '`' + (h[1] === 'partial' ? ' (partial)' : '')).join(', ') || 'none') + ' |');
  }
  o.push('', '## MCP Security Testing Guide: test by test', '', '| Test | Title | Best level | Checks | Other tools |', '|---|---|---|---|---|');
  for (const t of mstg.tests) {
    const oth = (map.other_tools[t.id] || []).map((x) => x.tool + ' (' + x.level + ')').join(', ');
    o.push('| ' + t.id + ' | ' + t.title + ' | ' + (best[t.id] || 'not covered by mcp-check') + ' | ' + ((by[t.id] || []).map(([c, l]) => '`' + c + '`' + (l === 'partial' ? ' (partial)' : '')).join(', ') || '') + ' | ' + (oth || '') + ' |');
  }
  o.push('', '## Checks with no mapping', '', 'These checks are mapped to nothing, on purpose: they grade spec shape, directory rules or description quality, which no listed test or risk asks about.', '');
  o.push(Object.entries(map.checks).filter(([, e]) => !e.mstg.length && !e.top10.length).map(([c]) => '`' + c + '`').join(', '), '');
  o.push('## Other tools', '', map.other_tools_note, '');
  for (const [id, l] of Object.entries(map.other_tools)) o.push('- ' + id + ': ' + l.map((x) => x.tool + ' (' + x.level + '): ' + x.note).join(' '));
  o.push('', '## Notes', '', '- The mapping is in [`taxonomy/owasp-mcp.json`](taxonomy/owasp-mcp.json). A test in `test/taxonomy.test.mjs` fails if a check has no entry, if an entry names a check that does not exist, or if an ID is not in the pinned lists.', '- The mapping is not part of the check catalogue: it changes no grade, no rubric version and no catalogue hash. Adding a `taxonomy` field to each check in the engine output is a follow-up (the engine file is vendored from the web checker, so it has to be done there first).', '- The Testing Guide has no release tag; it is pinned by commit. The Top 10 is v0.1 and its titles are not yet stable: the item MCP06 is "Prompt Injection via Contextual Payloads" on the project page and "Intent Flow Subversion" in the file name and the index.', '');
  return o.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const map = JSON.parse(readFileSync(MAP_PATH, 'utf8'));
  const ids = createRequire(import.meta.url)('../engine/core.js').CHECKS.map((c) => c.id);
  const bad = validate(map, ids);
  if (bad.length) { console.error(bad.join('\n')); process.exit(1); }
  const text = render(map);
  if (process.argv.includes('--check')) { process.exit(readFileSync(DOC_PATH, 'utf8') === text ? 0 : (console.error('docs/TAXONOMY.md is out of date: run node scripts/gen-taxonomy.mjs'), 1)); }
  writeFileSync(DOC_PATH, text);
}
